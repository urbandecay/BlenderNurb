"""Native NURBS topology edit, undo, proxy, and blendfile regression test.

Run in background mode with a fixture generated by NurbsTopologyIOTest, for
example::

  blender -b --python tests/python/bl_nurbs_topology.py -- --fixture /tmp/topology.blend
"""

import argparse
import os
import sys
import tempfile
import unittest

import bpy


def _parse_fixture_path():
    argv = sys.argv
    if "--" not in argv:
        raise RuntimeError("Expected -- --fixture <path> after Blender arguments")
    parser = argparse.ArgumentParser()
    parser.add_argument("--fixture", required=True)
    args = parser.parse_args(argv[argv.index("--") + 1 :])
    return os.path.abspath(args.fixture)


def _curve_metadata(curve):
    return (
        curve.component_id,
        curve.degree,
        curve.order,
        curve.dimension,
        curve.is_rational,
        tuple(curve.domain),
        tuple(curve.knots),
        tuple(
            (vertex.component_id, vertex.weight, vertex.select)
            for vertex in curve.control_vertices
        ),
    )


def _curve_snapshot(curve):
    return (
        _curve_metadata(curve),
        tuple((vertex.component_id, tuple(vertex.position)) for vertex in curve.control_vertices),
    )


def _geometry_snapshot(geometry):
    """Copy read-only RNA values; do not retain RNA element references."""
    return {
        "name": geometry.name,
        "has_topology": geometry.has_topology,
        "active_component_id": geometry.active_component_id,
        "curves": tuple(_curve_snapshot(curve) for curve in geometry.curves),
        "vertices": tuple(
            (vertex.component_id, tuple(vertex.position), vertex.select)
            for vertex in geometry.vertices
        ),
        "edges": tuple(
            (
                edge.component_id,
                edge.support_curve_id,
                tuple(edge.domain),
                edge.select,
            )
            for edge in geometry.edges
        ),
        "faces": tuple(
            (face.component_id, face.surface_id, face.loop_count, face.select)
            for face in geometry.faces
        ),
        "history": tuple(
            (item.component_id, item.type) for item in geometry.selection_history
        ),
    }


def _metadata_snapshot(geometry):
    return (
        tuple(_curve_metadata(curve) for curve in geometry.curves),
        tuple(
            (edge.component_id, edge.support_curve_id, tuple(edge.domain))
            for edge in geometry.edges
        ),
        tuple(
            (face.component_id, face.surface_id, face.loop_count) for face in geometry.faces
        ),
    )


def _proxy_face_ids(obj):
    depsgraph = bpy.context.evaluated_depsgraph_get()
    evaluated = obj.evaluated_get(depsgraph)
    mesh = evaluated.to_mesh()
    if mesh is None:
        raise AssertionError("Native NURBS object did not evaluate to a mesh proxy")
    try:
        low_attr = mesh.attributes.get(".nurbs_face_id_low")
        high_attr = mesh.attributes.get(".nurbs_face_id_high")
        if low_attr is None or high_attr is None:
            raise AssertionError("Evaluated proxy is missing NURBS face ID attributes")
        if low_attr.domain != "FACE" or high_attr.domain != "FACE":
            raise AssertionError("NURBS face ID attributes must use the FACE domain")
        if len(low_attr.data) != len(mesh.polygons) or len(high_attr.data) != len(mesh.polygons):
            raise AssertionError("NURBS face ID attributes must cover every proxy face")

        result = set()
        for low_item, high_item in zip(low_attr.data, high_attr.data):
            low = int(low_item.value) & 0xFFFFFFFF
            high = int(high_item.value) & 0xFFFFFFFF
            result.add((high << 32) | low)
        return result
    finally:
        evaluated.to_mesh_clear()


class NurbsTopologyNativeRegression(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.fixture_path = _parse_fixture_path()
        if not os.path.isfile(cls.fixture_path):
            raise RuntimeError("NURBS topology fixture does not exist: " + cls.fixture_path)

    def setUp(self):
        bpy.ops.wm.read_factory_settings(use_empty=True)
        with bpy.data.libraries.load(self.fixture_path, link=False) as (data_from, data_to):
            self.assertGreaterEqual(len(data_from.nurbs_geometries), 1)
            data_to.nurbs_geometries = list(data_from.nurbs_geometries)

        geometry = bpy.data.nurbs_geometries[0]
        self.geometry_name = geometry.name
        self.obj = bpy.data.objects.new("Native Topology Regression", geometry)
        bpy.context.scene.collection.objects.link(self.obj)
        self.obj.select_set(True)
        bpy.context.view_layer.objects.active = self.obj
        bpy.ops.object.mode_set(mode="EDIT")
        bpy.ops.nurbs.select_mode(type="EDGE")

    def _geometry(self):
        # Re-resolve the datablock after undo/redo instead of keeping RNA element references.
        return bpy.data.nurbs_geometries[self.geometry_name]

    def _assert_xyz_close(self, actual, expected, places=6):
        for actual_axis, expected_axis in zip(actual, expected):
            self.assertAlmostEqual(actual_axis, expected_axis, places=places)

    def _assert_translate_rejected(self):
        try:
            result = bpy.ops.transform.translate(value=(0.0, 0.0, 0.25))
        except RuntimeError as error:
            self.assertIn("Select one complete NURBS boundary", str(error))
            return
        self.assertEqual(result, {"CANCELLED"})

    def test_reject_multiple_boundaries_without_mutation(self):
        bpy.ops.nurbs.select_all(action="SELECT")
        before = _geometry_snapshot(self._geometry())

        self._assert_translate_rejected()

        self.assertEqual(_geometry_snapshot(self._geometry()), before)

    def test_reject_invalid_multiobject_transform_atomically(self):
        source_name = self.obj.name
        bpy.ops.object.mode_set(mode="OBJECT")
        bpy.ops.object.duplicate()
        duplicate_name = bpy.context.object.name
        self.assertNotEqual(
            bpy.data.objects[source_name].data,
            bpy.data.objects[duplicate_name].data,
            "The duplicate must own an independent NurbsGeometry ID",
        )

        # Make only the duplicate active and give it a selection spanning multiple supports.
        bpy.data.objects[source_name].select_set(False)
        bpy.data.objects[duplicate_name].select_set(True)
        bpy.context.view_layer.objects.active = bpy.data.objects[duplicate_name]
        bpy.ops.object.mode_set(mode="EDIT")
        bpy.ops.nurbs.select_mode(type="EDGE")
        bpy.ops.nurbs.select_all(action="SELECT")
        bpy.ops.object.mode_set(mode="OBJECT")

        source_obj = bpy.data.objects[source_name]
        duplicate_obj = bpy.data.objects[duplicate_name]
        source_obj.select_set(True)
        duplicate_obj.select_set(True)
        bpy.context.view_layer.objects.active = source_obj
        bpy.ops.object.mode_set(mode="EDIT")
        bpy.ops.nurbs.select_mode(type="EDGE")

        before = {
            source_name: _geometry_snapshot(bpy.data.objects[source_name].data),
            duplicate_name: _geometry_snapshot(bpy.data.objects[duplicate_name].data),
        }
        self._assert_translate_rejected()
        after = {
            source_name: _geometry_snapshot(bpy.data.objects[source_name].data),
            duplicate_name: _geometry_snapshot(bpy.data.objects[duplicate_name].data),
        }
        self.assertEqual(after, before)

    def test_native_seam_edit_undo_split_and_roundtrip(self):
        geometry = self._geometry()
        self.assertTrue(geometry.has_topology)
        baseline = _geometry_snapshot(geometry)
        baseline_metadata = _metadata_snapshot(geometry)
        self.assertEqual(len(baseline["faces"]), 2)
        self.assertEqual(sorted(face[2] for face in baseline["faces"]), [1, 2])

        selected_before = {edge[0] for edge in baseline["edges"] if edge[3]}
        self.assertEqual(len(selected_before), 2, "Fixture should select both split seam edges")
        self.assertIn(baseline["active_component_id"], selected_before)
        self.assertTrue(baseline["history"], "Fixture should preserve selection history")
        self.assertTrue(
            any(item_id in selected_before and item_type == "EDGE"
                for item_id, item_type in baseline["history"]),
            "Fixture history should include a selected seam edge",
        )

        # The fixture exposes a cylindrical seam at z=1 between fixed z=0 and z=2 rows.
        baseline_vertices = {item[0]: item[1] for item in baseline["vertices"]}
        seam_ids = {component_id for component_id, pos in baseline_vertices.items()
                    if abs(pos[2] - 1.0) < 1e-6}
        self.assertGreaterEqual(len(seam_ids), 3)
        self.assertTrue(any(abs(pos[2]) < 1e-6 for pos in baseline_vertices.values()))
        self.assertTrue(any(abs(pos[2] - 2.0) < 1e-6 for pos in baseline_vertices.values()))

        bpy.ops.ed.undo_push()
        result = bpy.ops.transform.translate(value=(0.0, 0.0, 0.25))
        self.assertEqual(result, {"FINISHED"})
        translated = _geometry_snapshot(self._geometry())
        translated_vertices = {item[0]: item[1] for item in translated["vertices"]}
        self.assertEqual(set(baseline_vertices), set(translated_vertices))
        for component_id, before in baseline_vertices.items():
            after = translated_vertices[component_id]
            if before[2] <= 1.0:
                # Face A is linear in V from z=0 to z=1.
                expected_z = before[2] + 0.25 * before[2]
            else:
                # Face B is linear in V from z=1 to z=2, with its top fixed.
                expected_z = before[2] + 0.25 * (2.0 - before[2])
            if component_id in seam_ids:
                self.assertAlmostEqual(expected_z, 1.25, places=6)
            self._assert_xyz_close(after, (before[0], before[1], expected_z))
        self.assertEqual(baseline_metadata, _metadata_snapshot(self._geometry()))

        # Seed the post-edit state for background-mode global undo implementations.
        bpy.ops.ed.undo_push()
        self.assertEqual(bpy.ops.ed.undo(), {"FINISHED"})
        undone = _geometry_snapshot(self._geometry())
        self.assertEqual(undone, baseline, "Undo must restore topology, active ID, and history")
        self.assertEqual(bpy.ops.ed.redo(), {"FINISHED"})
        redone = _geometry_snapshot(self._geometry())
        self.assertEqual(redone, translated, "Redo must restore the translated seam state")

        before_split = redone
        before_split_metadata = _metadata_snapshot(self._geometry())
        before_vertex_count = len(before_split["vertices"])
        before_face_loop_counts = tuple(face[2] for face in before_split["faces"])
        selected_supports = {
            edge[1] for edge in before_split["edges"] if edge[0] in selected_before
        }

        result = bpy.ops.nurbs.edge_split(factor=0.5)
        self.assertEqual(result, {"FINISHED"})
        split = _geometry_snapshot(self._geometry())
        self.assertEqual(len(split["vertices"]), before_vertex_count + 2)
        self.assertEqual(len(split["edges"]), len(before_split["edges"]) + 2)
        self.assertEqual(tuple(face[2] for face in split["faces"]), before_face_loop_counts)
        self.assertEqual(len(split["faces"]), len(before_split["faces"]))

        selected_after = {edge[0] for edge in split["edges"] if edge[3]}
        self.assertEqual(len(selected_after), 4)
        self.assertIn(split["active_component_id"], selected_after)
        edge_ids = {edge[0] for edge in split["edges"]}
        for item_id, item_type in split["history"]:
            if item_type == "EDGE":
                self.assertIn(item_id, edge_ids, "Selection history must remap to existing edges")
                self.assertIn(item_id, selected_after, "Remapped history edge should remain selected")
        split_supports = {edge[1] for edge in split["edges"] if edge[0] in selected_after}
        self.assertEqual(split_supports, selected_supports)
        self.assertEqual(before_split_metadata[0], _metadata_snapshot(self._geometry())[0])
        self.assertEqual(before_split_metadata[2], _metadata_snapshot(self._geometry())[2])

        real_face_ids = {int(face[0]) for face in split["faces"]}
        self.assertTrue(real_face_ids)
        self.assertEqual(_proxy_face_ids(self.obj), real_face_ids)

        post_split_snapshot = _geometry_snapshot(self._geometry())
        with tempfile.TemporaryDirectory() as temp_dir:
            temp_path = os.path.join(temp_dir, "topology_roundtrip.blend")
            bpy.ops.wm.save_as_mainfile(filepath=temp_path)
            bpy.ops.wm.open_mainfile(filepath=temp_path)
            reopened_geometry = next(
                geometry
                for geometry in bpy.data.nurbs_geometries
                if geometry.name == post_split_snapshot["name"]
            )
            reopened = _geometry_snapshot(reopened_geometry)
            self.assertEqual(reopened, post_split_snapshot)
            reopened_obj = next(
                obj for obj in bpy.data.objects if obj.type == "NURBS" and obj.data == reopened_geometry
            )
            self.assertEqual(
                _proxy_face_ids(reopened_obj),
                {int(face[0]) for face in reopened["faces"]},
            )


if __name__ == "__main__":
    unittest.main(argv=[sys.argv[0]])
